/**
 * Generate src/tag-strings.ts from the inlang message files (messages/<locale>.json),
 * so the strings compile into dist (no JSON copy / no runtime fs).
 *
 *   node ./script/build-strings.ts
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, basename } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const messagesDir = join(root, "messages");

const files = (await readdir(messagesDir)).filter((f) => f.endsWith(".json"));
const locales: Record<string, Record<string, string>> = {};

for (const f of files.sort()) {
  const locale = basename(f, ".json");
  const raw = JSON.parse(await readFile(join(messagesDir, f), "utf8")) as Record<string, string>;
  const strings: Record<string, string> = {};
  for (const [k, v] of Object.entries(raw)) {
    if (k === "$schema") continue;
    strings[k] = v;
  }
  locales[locale] = strings;
}

let out = "// This file is auto-generated by script/build-strings.ts\n";
out += "// Do not edit manually - edit messages/<locale>.json and run 'yarn build-strings'.\n\n";
out += 'export const baseLocale = "en";\n\n';
out += "export const tagStrings: Record<string, Record<string, string>> = ";
out += JSON.stringify(locales, null, 2);
out += ";\n";

await writeFile(join(root, "src", "tag-strings.ts"), out);
const counts = Object.entries(locales)
  .map(([l, s]) => `${l}:${Object.keys(s).length}`)
  .join(", ");
console.log(`Wrote src/tag-strings.ts (${counts}).`);
